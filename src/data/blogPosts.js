export const blogPostBySlug = Object.fromEntries(blogPosts.map((post) => [post.slug, post]))

export const blogCategories = [...new Set(blogPosts.map(post => post.category))].sort()

export const getRelatedPosts = (currentSlug, limit = 3) => {
  const currentPost = blogPostBySlug[currentSlug]
  if (!currentPost) return []
  
  return blogPosts
    .filter(post => post.slug !== currentSlug && post.category === currentPost.category)
    .sort((a, b) => new Date(b.date) - new Date(a.date))
    .slice(0, limit)
}

export const searchPosts = (query) => {
  const lowerQuery = query.toLowerCase()
  return blogPosts.filter(post =>
    post.title.toLowerCase().includes(lowerQuery) ||
    post.excerpt.toLowerCase().includes(lowerQuery) ||
    post.tags?.some(tag => tag.toLowerCase().includes(lowerQuery))
  )
}
